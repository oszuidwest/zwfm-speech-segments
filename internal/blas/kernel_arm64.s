#include "textflag.h"

// func kernel8x12(k int, a, b, c *float32, ldc int)
// c[r*ldc : r*ldc+12] += sum over p of a[p*8+r] * b[p*12 : p*12+12], r = 0..7.
// V0-V1 hold 8 values of A, V2-V4 a row of B, and V8-V31 the block (row r in
// V(8+3r) to V(10+3r)).
//
// The Go assembler has no by-element FMLA (FMLA Vd.4S, Vn.4S, Vm.S[i]), so
// each one is emitted as WORD with its instruction text in the comment.
TEXT ·kernel8x12(SB), NOSPLIT, $0-40
	MOVD k+0(FP), R0
	MOVD a+8(FP), R1
	MOVD b+16(FP), R2
	MOVD c+24(FP), R3
	MOVD ldc+32(FP), R4
	LSL $2, R4 // row stride in bytes
	VEOR V8.B16, V8.B16, V8.B16
	VEOR V9.B16, V9.B16, V9.B16
	VEOR V10.B16, V10.B16, V10.B16
	VEOR V11.B16, V11.B16, V11.B16
	VEOR V12.B16, V12.B16, V12.B16
	VEOR V13.B16, V13.B16, V13.B16
	VEOR V14.B16, V14.B16, V14.B16
	VEOR V15.B16, V15.B16, V15.B16
	VEOR V16.B16, V16.B16, V16.B16
	VEOR V17.B16, V17.B16, V17.B16
	VEOR V18.B16, V18.B16, V18.B16
	VEOR V19.B16, V19.B16, V19.B16
	VEOR V20.B16, V20.B16, V20.B16
	VEOR V21.B16, V21.B16, V21.B16
	VEOR V22.B16, V22.B16, V22.B16
	VEOR V23.B16, V23.B16, V23.B16
	VEOR V24.B16, V24.B16, V24.B16
	VEOR V25.B16, V25.B16, V25.B16
	VEOR V26.B16, V26.B16, V26.B16
	VEOR V27.B16, V27.B16, V27.B16
	VEOR V28.B16, V28.B16, V28.B16
	VEOR V29.B16, V29.B16, V29.B16
	VEOR V30.B16, V30.B16, V30.B16
	VEOR V31.B16, V31.B16, V31.B16
	CBZ R0, done
loop:
	VLD1.P 32(R1), [V0.S4, V1.S4]
	VLD1.P 48(R2), [V2.S4, V3.S4, V4.S4]
	WORD $0x4f801048 // FMLA V8.4S, V2.4S, V0.S[0]
	WORD $0x4f801069 // FMLA V9.4S, V3.4S, V0.S[0]
	WORD $0x4f80108a // FMLA V10.4S, V4.4S, V0.S[0]
	WORD $0x4fa0104b // FMLA V11.4S, V2.4S, V0.S[1]
	WORD $0x4fa0106c // FMLA V12.4S, V3.4S, V0.S[1]
	WORD $0x4fa0108d // FMLA V13.4S, V4.4S, V0.S[1]
	WORD $0x4f80184e // FMLA V14.4S, V2.4S, V0.S[2]
	WORD $0x4f80186f // FMLA V15.4S, V3.4S, V0.S[2]
	WORD $0x4f801890 // FMLA V16.4S, V4.4S, V0.S[2]
	WORD $0x4fa01851 // FMLA V17.4S, V2.4S, V0.S[3]
	WORD $0x4fa01872 // FMLA V18.4S, V3.4S, V0.S[3]
	WORD $0x4fa01893 // FMLA V19.4S, V4.4S, V0.S[3]
	WORD $0x4f811054 // FMLA V20.4S, V2.4S, V1.S[0]
	WORD $0x4f811075 // FMLA V21.4S, V3.4S, V1.S[0]
	WORD $0x4f811096 // FMLA V22.4S, V4.4S, V1.S[0]
	WORD $0x4fa11057 // FMLA V23.4S, V2.4S, V1.S[1]
	WORD $0x4fa11078 // FMLA V24.4S, V3.4S, V1.S[1]
	WORD $0x4fa11099 // FMLA V25.4S, V4.4S, V1.S[1]
	WORD $0x4f81185a // FMLA V26.4S, V2.4S, V1.S[2]
	WORD $0x4f81187b // FMLA V27.4S, V3.4S, V1.S[2]
	WORD $0x4f81189c // FMLA V28.4S, V4.4S, V1.S[2]
	WORD $0x4fa1185d // FMLA V29.4S, V2.4S, V1.S[3]
	WORD $0x4fa1187e // FMLA V30.4S, V3.4S, V1.S[3]
	WORD $0x4fa1189f // FMLA V31.4S, V4.4S, V1.S[3]
	SUBS $1, R0
	BNE loop
done:
	VLD1 (R3), [V0.S4, V1.S4, V2.S4]
	VFADD V0.S4, V8.S4, V0.S4
	VFADD V1.S4, V9.S4, V1.S4
	VFADD V2.S4, V10.S4, V2.S4

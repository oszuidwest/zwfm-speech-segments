	VFADD V0.S4, V26.S4, V0.S4
	VFADD V1.S4, V27.S4, V1.S4
	VFADD V2.S4, V28.S4, V2.S4
	VST1 [V0.S4, V1.S4, V2.S4], (R3)
	ADD R4, R3
	VLD1 (R3), [V0.S4, V1.S4, V2.S4]
	VFADD V0.S4, V29.S4, V0.S4
	VFADD V1.S4, V30.S4, V1.S4
	VFADD V2.S4, V31.S4, V2.S4
	VST1 [V0.S4, V1.S4, V2.S4], (R3)
	RET

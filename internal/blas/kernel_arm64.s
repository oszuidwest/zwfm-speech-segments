	VLD1 (R3), [V0.S4, V1.S4, V2.S4]
	VFADD V0.S4, V17.S4, V0.S4
	VFADD V1.S4, V18.S4, V1.S4
	VFADD V2.S4, V19.S4, V2.S4
	VST1 [V0.S4, V1.S4, V2.S4], (R3)
	ADD R4, R3
	VLD1 (R3), [V0.S4, V1.S4, V2.S4]
	VFADD V0.S4, V20.S4, V0.S4
	VFADD V1.S4, V21.S4, V1.S4
	VFADD V2.S4, V22.S4, V2.S4
	VST1 [V0.S4, V1.S4, V2.S4], (R3)
	ADD R4, R3
	VLD1 (R3), [V0.S4, V1.S4, V2.S4]
	VFADD V0.S4, V23.S4, V0.S4
	VFADD V1.S4, V24.S4, V1.S4
	VFADD V2.S4, V25.S4, V2.S4
